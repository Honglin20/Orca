"""train_pipeline.py — KD-NAS unified training script (teacher + distill + eval modes).

Generated by the ``kd-train-script`` agent.  Self-contained: copies the user's
loss / dataloader / optimizer / eval-metric logic inline (never imports the
user's project), loads teacher/student models **by path** via
:mod:`importlib.util`, and runs on a single device (no distributed
data-parallel launch, no torchrun, no architecture sampling — KD-NAS uses a
``ThreadPoolExecutor`` round-robin pool at the workflow level, not inside the
training script).

Three modes
-----------
* ``--mode teacher``   — train a teacher with pure ``user_task_loss``, save a
  checkpoint consumable by ``teacher_setup`` (state_dict + build_cfg).
* ``--mode distill``   — train a student with ``user_task_loss`` + KD loss
  (assembled via :func:`kd.compose.build_kd_loss`), save the student ckpt.
* ``--mode eval``      — load a student ckpt, run the user's eval metric
  (discovered by the agent from the user repo's eval script, e.g.
  ``test_student.py``), and emit the accuracy protocol consumed by
  ``train_pool``. Read-only: no checkpoint is written; this mode replaces the
  old ``measure_student --eval_command`` path.

When the ``{{USER_TRAIN_MODULE}}`` / ``{{USER_EVAL_MODULE}}`` placeholders are
left unexpanded the script runs on placeholder fallbacks (dummy MSE loss +
random re-iterable loader + dummy NMSE eval) so it is smoke-testable
standalone before the agent specialises it.

Generation contract (verifier cross-checks this)
------------------------------------------------
* Stdout keys (teacher mode): ``TEACHER_CKPT: <path>`` + ``TASK_LOSS_FINAL: <float>``
* Stdout keys (distill mode): ``STUDENT_CKPT: <path>`` + ``KD_LOSS_FINAL: <float>``
  + ``KD_PROXY_MSE: <float>``
* Stdout keys (eval mode): ``STUDENT_ACCURACY: <float>`` +
  ``STUDENT_ACCURACY_KIND: <nmse|mse|ber|snr|acc>`` + ``MET_ACCURACY: <bool>``
  + ``ACCURACY_CONFIDENCE: high|low`` (no ckpt written — read-only evaluation).
* Teacher ckpt schema: ``{state_dict, build_cfg, variant_id, epochs, final_loss, mode}``
* Student ckpt schema: ``{student_state_dict, variant_id, student_cfg, kd_config,
  epochs, proxy_mse, mode}``
"""

