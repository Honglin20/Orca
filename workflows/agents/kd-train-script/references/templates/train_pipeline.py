# ---------------------------------------------------------------------------
# Placeholder fallbacks — keep the template runnable before specialisation.
# ---------------------------------------------------------------------------
def _placeholder_user_loss(s_out: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
    """Default user task loss — MSE to target ``y`` (same shape as student output)."""
    return F.mse_loss(s_out, y)


class _PlaceholderDataLoader:
    """Re-iterable random (x, y) batch generator for smoke tests.

    Mirrors the ``examples/kd-nas-demo/train.py`` ``_RandomDataLoader`` contract:
    each ``iter()`` yields a fresh stream of ``n_batches`` random batches with
    shape aligned to ``DUMMY_INPUT``.  Re-iterable so multi-epoch training
    doesn't exhaust after the first epoch.
    """

    def __init__(
        self,
        batch_size: int = 4,
        n_batches: int = 8,
        shape: Tuple[int, ...] = (1, 4, 48, 64, 1),
    ) -> None:
        self.batch_size = batch_size
        self.n_batches = n_batches
        self.shape = shape

    def __iter__(self) -> Iterator[Tuple[torch.Tensor, torch.Tensor]]:
        inner = tuple(self.shape[1:])
        for _ in range(self.n_batches):
            x = torch.randn(self.batch_size, *inner)
            y = torch.randn(self.batch_size, *inner)
            yield x, y

    def __len__(self) -> int:
        return self.n_batches


def _placeholder_build_dataloader(batch_size: int = 4) -> _PlaceholderDataLoader:
    return _PlaceholderDataLoader(batch_size=batch_size)


def _placeholder_user_eval(student: nn.Module, device) -> tuple[float, str]:
    """Default user eval metric — NMSE on one random batch (mirrors the
    placeholder dataloader's inner shape). Returns ``(nmse, "nmse")`` so the
    eval mode is smoke-testable before the agent specialises it.

    The agent replaces this with the user's real eval metric (ported from the
    user repo's eval script) — same signature ``(student, device) -> (value, kind)``.
    """
    inner = (4, 48, 64, 1)  # demo-aligned with _PlaceholderDataLoader.shape
    x = torch.randn(1, *inner).to(device)
    y = torch.randn(1, *inner).to(device)
    student.eval()
    with torch.no_grad():
        out = student(x)
    out = out.reshape_as(y)
    num = float(torch.sum((out - y) ** 2).item())
    den = float(torch.sum(y ** 2).item()) + 1e-12
    return num / den, "nmse"


def _load_user_train() -> Tuple[Callable, Callable]:
    """Resolve user task loss + dataloader builders.

    Returns ``(loss_fn, build_dataloader)``.  When the placeholders are
    unexpanded (``{{...}}``), returns placeholder fallbacks so the template
    runs end-to-end without the user's code present.  Otherwise imports the
    user's train module by path or module name.

    ``build_dataloader`` may be absent in the user module — the KD-NAS user
    contract only guarantees ``compute_loss``; in that case fall back to the
    placeholder loader and emit a stderr note (fail loud on loss, lenient on
    loader with explicit fallback).
    """
    if USER_TRAIN_MODULE.startswith("{{"):
        return _placeholder_user_loss, _placeholder_build_dataloader

    if os.path.isfile(USER_TRAIN_MODULE):
        spec = importlib.util.spec_from_file_location("_user_train", USER_TRAIN_MODULE)
        if spec is None or spec.loader is None:
            raise ImportError(f"cannot construct import spec for {USER_TRAIN_MODULE}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    else:
        module = importlib.import_module(USER_TRAIN_MODULE)

    if not hasattr(module, USER_LOSS_FN):
        raise AttributeError(
            f"user train module {USER_TRAIN_MODULE!r} has no loss fn {USER_LOSS_FN!r}"
        )
    loss_fn = getattr(module, USER_LOSS_FN)
    build_dl = getattr(module, "build_dataloader", None)
    if build_dl is None:
        # KD-NAS user contract does not require build_dataloader — explicit fallback.
        print(
            f"[train_pipeline] NOTE: user module {USER_TRAIN_MODULE!r} has no "
            f"build_dataloader; using placeholder random loader.",
            file=sys.stderr,
        )
        build_dl = _placeholder_build_dataloader
    return loss_fn, build_dl


def _load_user_eval() -> Callable:
    """Resolve the user eval metric function.

    Returns a callable ``fn(student: nn.Module, device) -> (value: float,
    kind: str)``. When the placeholder is unexpanded (``{{...}}``), returns the
    placeholder eval fn so the template runs end-to-end. Otherwise imports the
    user's eval module (discovered from the user repo's eval script, e.g.
    ``test_student.py``) by path or module name and resolves ``USER_EVAL_FN``.

    The agent ports the user's eval logic (data loading + metric computation)
    into this callable — it must be self-contained (no user-project imports).
    When the user's eval script does not expose a matching-signature function,
    the agent inlines an ``evaluate_student`` helper into the generated script
    and points ``USER_EVAL_MODULE``/``USER_EVAL_FN`` at it.
    """
    if USER_EVAL_MODULE.startswith("{{"):
        return _placeholder_user_eval

    if os.path.isfile(USER_EVAL_MODULE):
        spec = importlib.util.spec_from_file_location("_user_eval", USER_EVAL_MODULE)
        if spec is None or spec.loader is None:
            raise ImportError(f"cannot construct import spec for {USER_EVAL_MODULE}")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    else:
        module = importlib.import_module(USER_EVAL_MODULE)

    if not hasattr(module, USER_EVAL_FN):
        raise AttributeError(
            f"user eval module {USER_EVAL_MODULE!r} has no eval fn {USER_EVAL_FN!r}"
        )
    return getattr(module, USER_EVAL_FN)


# ---------------------------------------------------------------------------
# Model load by path (KD-NAS teacher/student contract: build_model + DUMMY_INPUT).
# ---------------------------------------------------------------------------
def _load_model_by_path(model_path: str, build_fn: str, cfg: dict) -> nn.Module:
    """Import a model ``.py`` by absolute path and call ``build_fn(**cfg)``.

    Inserts the model file's directory into ``sys.path`` so shared-block
    imports (e.g. ``from _model8_blocks import ...``) resolve for KD-NAS
    variants living in ``knowledge_base/families/receiver/``.  Re-registers
    the module in ``sys.modules`` so downstream ``importlib`` hits cache.
    """
    model_path = os.path.abspath(model_path)
    if not os.path.isfile(model_path):
        raise FileNotFoundError(f"model_path not found: {model_path}")
    model_dir = os.path.dirname(model_path)
    if model_dir not in sys.path:
        sys.path.insert(0, model_dir)
    module_name = Path(model_path).stem
    spec = importlib.util.spec_from_file_location(module_name, model_path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot construct import spec for {model_path}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = mod
    spec.loader.exec_module(mod)
    if not hasattr(mod, build_fn):
        raise AttributeError(
            f"{model_path} has no build fn {build_fn!r}; available: "
            f"{[n for n in dir(mod) if not n.startswith('_')]}"
        )
    return getattr(mod, build_fn)(**cfg)


def _resolve_device(name: str) -> torch.device:
    if name == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    return torch.device(name)


def _build_dataloader(build_dataloader: Callable, batch_size: int):
    """Call ``build_dataloader()``; fall back to ``build_dataloader(batch_size=)``.

    The user contract permits either signature; try the no-arg form first
    (matches ``examples/kd-nas-demo/train.py``) and gracefully accept the
    kwargs form.
    """
    try:
        return build_dataloader()
    except TypeError:
        return build_dataloader(batch_size=batch_size)


def _make_live_push(variant_id: str, mode: str):
    """Per-epoch live chart push (best-effort, never kills the training loop).

    Mirrors ``train_adapter_template._make_live_push``: lazy import
    ``orca.chart.render_chart``; on any failure (import error, push error)
    degrade to a no-op or stderr warning.  Same ``label``+``title`` re-push
    = refresh semantics (dedup).
    """
    try:
        from orca.chart import render_chart  # type: ignore
    except Exception:
        render_chart = None  # type: ignore
    label = f"kd-{mode}-{variant_id}"
    title = f"{mode} loss — {variant_id}"

    def push(curve: list) -> None:
        if render_chart is None:
            return
        try:
            render_chart(
                chart_type="line",
                data=curve,
                label=label,
                title=title,
                x="epoch",
                y="loss",
                x_label="epoch",
                y_label="loss（越低越好）",
                caption=f"{mode} training loss per-epoch (variant={variant_id})",
            )
        except Exception as e:  # best-effort sidecar: never abort training
            print(
                f"[train_pipeline:{mode}] WARN: render_chart failed "
                f"(ignored): {type(e).__name__}: {e}",
                file=sys.stderr,
            )

    return push


def _maybe_bootstrap_env(env_anchor: str) -> None:
    """best-effort ORCA env bootstrap from per-run artifacts anchor.

    Prevents the agent-spawned bash losing ``ORCA_CHART_SOCK`` (which would
    make live chart pushes silently no-op).  Failure is non-fatal — only a
    stderr warning is emitted.
    """
    if not env_anchor:
        return
    try:
        from orca.chart._env import load_run_env_from_artifacts  # type: ignore

        load_run_env_from_artifacts(env_anchor)
    except Exception as e:
        print(
            f"[train_pipeline] WARN: env bootstrap failed "
            f"(live chart may not push): {type(e).__name__}: {e}",
            file=sys.stderr,
        )


