    if args.user_eval_import:
        USER_EVAL_MODULE = args.user_eval_import
    if args.user_eval_fn:
        USER_EVAL_FN = args.user_eval_fn
    if args.mode == "eval":
        # eval mode is read-only: it needs only the user eval metric, not the
        # train loss/dataloader — resolve it independently so eval never depends
        # on train.py's compute_loss being importable.
        user_eval = _load_user_eval()
