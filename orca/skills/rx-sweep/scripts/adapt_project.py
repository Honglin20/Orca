    #         按 adaptation-guide 方式 B 在 utils/<训练脚本>.py 里改实例化点：
    #         from rx_models import get_model, RxConfig
    #         model = get_model(args.model, cfg)
    model = get_model(args.model, cfg)
    model.eval()

    # dummy 前向 smoke（I/O 对齐 rx_models 全方案：cfg.io_shape = [1,P,F,S,1]）
    shape = tuple(cfg.io_shape)
    x = torch.zeros(shape, dtype=torch.float32)
    io_in = list(shape)
    io_out = []
    passed = False
    try:
        with torch.no_grad():
            y = model(x)
        io_in = list(x.shape)
        io_out = list(y.shape)
        passed = (io_in == cfg.io_shape and io_out == cfg.io_shape)
    except Exception as e:  # noqa: BLE001 —— smoke 失败不致命，GATE 报 FAIL
        print(f"[RX-GATE] forward smoke crashed: {e!r}",
              file=sys.stderr, flush=True)

    # GATE 行用同一份 cfg（M4：避免 GATE 硬编码与 get_model 脱节）
    _gate_line(args.model, cfg, io_in, io_out, passed)
    return model, cfg, passed


