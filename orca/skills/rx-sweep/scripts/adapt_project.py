def _fmt_shape(s):
    """[1,4,48,32,1] -> '[1,4,48,32,1]'（无空格逗号分隔）。

    gate_check._parse_kv 按空格切 token，list str 化默认带空格（'[1, 4, ...]'）会让
    io_in 被截成 '[1,'，导致 io_in mismatch 误报（B1）。
    """
    return "[" + ",".join(str(int(x)) for x in s) + "]"


def _gate_line(model, cfg, io_in, io_out, passed):
    """打印一行 [RX-GATE] key=val ...（contracts.md §3 格式，无空格逗号）。

    维度全从 cfg 读（M4：单一真相源）——P/F/S/blocks/embed 一份 cfg，GATE 行与
    get_model 共享，杜绝硬编码维度漂移（原 pure_cnn_model 64/32 bug 的根治点）。
    """
    fields = [
        f"model={model}",
        f"P={cfg.num_ports}",
        f"F={cfg.num_subcarriers}",
        f"S={cfg.num_symbols}",
        f"blocks={cfg.num_blocks}",
        f"embed={cfg.embed_dim}",
        f"io_in={_fmt_shape(io_in)}",
        f"io_out={_fmt_shape(io_out)}",
        f"gate={'PASS' if passed else 'FAIL'}",
    ]
    print("[RX-GATE] " + " ".join(fields), flush=True)


def _smoke_and_gate(args):
    """建模型 + dummy 前向 smoke + 打 GATE 行。返回 (model, cfg, passed)。"""
    # === 维度 cfg 构造点（单一真相源）===
    # <<<TODO: 用户微调>>> 默认 RxConfig(num_symbols=32, ...)；若用户工程有 cfg 对象
    #         （如 utils.train_rx.cfg / 顶层 config.py 的实例），适配 agent 在此注入，
